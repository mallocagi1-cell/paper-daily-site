/* Paper Daily share poster (style 1, cream magazine card, 1080x1440), drawn on a canvas in the reader's browser.
   Loaded on demand by share/share.js. Fonts are per-page subsets served from this site (share/f/*.woff2), and the QR
   matrix comes from the page data, so the canvas stays untainted and can be exported. Generated by src/share.py. */
(function(){
var W=1080,H=1440,P=86,ACC='#D9643A',INK='#141414',INK2='#4A4A4A',MUTE='#8C8C8C',LINE='#E2DDD6',BG='#FBF6EC';
var FAM={disp:'PDPdisp',serif:'PDPserif',sans:'PDPsans',sansb:'PDPsansb',fb:'PDPfb'};
var fontsP=null;
function loadFonts(D){if(fontsP)return fontsP;if(!window.FontFace||!document.fonts)return Promise.reject(new Error('FontFace'));
 var ps=Object.keys(FAM).map(function(k){var f=new FontFace(FAM[k],'url('+D.fonts[k]+') format("woff2")');return f.load().then(function(x){document.fonts.add(x)})});
 var to=new Promise(function(_,rej){setTimeout(function(){rej(new Error('font timeout'))},20000)});
 fontsP=Promise.race([Promise.all(ps),to]);fontsP.catch(function(){fontsP=null});return fontsP}
/* stacks mirror JS_FALLBACK in share.py: disp -> serif -> sans, serif -> sans, then the per-page fallback face */
var STACK={disp:['disp','serif','sans'],serif:['serif','sans'],sans:['sans'],sansb:['sansb']};
function F(px,k){return px+'px '+STACK[k].map(function(r){return FAM[r]}).join(', ')+', '+FAM.fb+', sans-serif'}
var CJK=/[\u2e80-\u9fff\uac00-\ud7af\uf900-\ufaff\uff00-\uffef\u3000-\u303f]/;
function tokens(s){var out=[],buf='';for(var i=0;i<s.length;i++){var c=s[i];
 if(CJK.test(c)){if(buf){out.push(buf);buf=''}out.push(c)}else if(c===' '){buf+=' ';out.push(buf);buf=''}else buf+=c}
 if(buf)out.push(buf);return out}
function ellip(ctx,s,w){if(ctx.measureText(s).width<=w)return s;while(s.length&&ctx.measureText(s.replace(/\s+$/,'')+'\u2026').width>w)s=s.slice(0,-1);return s.replace(/[\s,，、;；:：]+$/,'')+'\u2026'}
function wrap(ctx,text,w,max){var t=tokens(text),lines=[],cur='';
 for(var i=0;i<t.length;i++){var nx=cur+t[i];
  if(ctx.measureText(nx.replace(/\s+$/,'')).width<=w){cur=nx;continue}
  if(!cur){var part='';for(var j=0;j<t[i].length;j++){if(ctx.measureText(part+t[i][j]).width>w){lines.push(part);part=''}part+=t[i][j]}cur=part;continue}
  /* keep CJK closing punctuation off the start of a line */
  if(/^[，。、；：！？）》」』”’,.;:!?)]/.test(t[i])&&ctx.measureText(nx).width<=w+ctx.measureText(t[i]).width){cur=nx;continue}
  lines.push(cur.replace(/\s+$/,''));cur=t[i]}
 if(cur)lines.push(cur.replace(/\s+$/,''));
 if(lines.length>max){var keep=lines.slice(0,max),l=keep[max-1].replace(/\s+$/,'');
  while(l.length&&ctx.measureText(l+'\u2026').width>w)l=l.slice(0,-1);keep[max-1]=l.replace(/[\s,，、;；:：。.]+$/,'')+'\u2026';return keep}
 return lines}
function spaced(ctx,s,x,y,sp){for(var i=0;i<s.length;i++){ctx.fillText(s[i],x,y);x+=ctx.measureText(s[i]).width+sp}return x}
function spacedW(ctx,s,sp){var w=0;for(var i=0;i<s.length;i++)w+=ctx.measureText(s[i]).width+sp;return w-sp}
function rr(ctx,x,y,w,h,r){ctx.beginPath();ctx.moveTo(x+r,y);ctx.arcTo(x+w,y,x+w,y+h,r);ctx.arcTo(x+w,y+h,x,y+h,r);ctx.arcTo(x,y+h,x,y,r);ctx.arcTo(x,y,x+w,y,r);ctx.closePath()}
function mark(ctx,x,y,s){var k=s/64;ctx.save();ctx.translate(x,y);ctx.scale(k,k);
 ctx.fillStyle=ACC;rr(ctx,0,0,64,64,14);ctx.fill();ctx.fillStyle=BG;rr(ctx,13,20,31,35,3.5);ctx.fill();
 ctx.fillStyle=ACC;rr(ctx,19,31,12,4,2);ctx.fill();ctx.fillStyle='#1E1A16';rr(ctx,19,39,19,4,2);ctx.fill();rr(ctx,19,47,12,4,2);ctx.fill();
 if(window.Path2D){var sp=new Path2D('M44 6Q46.08 16.92 57 19Q46.08 21.08 44 32Q41.92 21.08 31 19Q41.92 16.92 44 6Z');
  ctx.lineWidth=3.5;ctx.lineJoin='round';ctx.strokeStyle=ACC;ctx.stroke(sp);ctx.fillStyle='#FFF3D6';ctx.fill(sp);
  ctx.fill(new Path2D('M55 28.8Q55.672 32.328 59.2 33Q55.672 33.672 55 37.2Q54.328 33.672 50.8 33Q54.328 32.328 55 28.8Z'))}
 ctx.restore()}
function qrBits(D){var h=D.qr.d,b='';for(var i=0;i<h.length;i++)b+=('000'+parseInt(h[i],16).toString(2)).slice(-4);return b}
function layout(ctx,D,o){ /* returns the y where content ends; draws when o.draw */
 var d=o.draw,y=P,t=D.p,cw=W-2*P,g=o.gap||0;
 ctx.textBaseline='top';
 ctx.font=F(24,'sansb');ctx.fillStyle=ACC;if(d)spaced(ctx,t.kicker,P,y,3.8);y+=24+22;
 ctx.font=F(24,'sans');var x=P;t.chips.forEach(function(c){var w=ctx.measureText(c).width+32;if(x+w>W-P)return;
  if(d){ctx.strokeStyle=LINE;ctx.lineWidth=2;rr(ctx,x+1,y+1,w-2,42,21);ctx.stroke();ctx.fillStyle=INK2;ctx.fillText(c,x+16,y+9)}x+=w+14});
 y+=42+40;
 ctx.font=F(o.ts,'disp');var tl=wrap(ctx,t.title,cw,4),lh=Math.round(o.ts*1.12);
 if(d){ctx.fillStyle=INK;tl.forEach(function(l,i){ctx.fillText(l,P,y+i*lh)})}y+=tl.length*lh+34+g;
 if(d){ctx.fillStyle=ACC;ctx.fillRect(P,y,110,8)}y+=8+30;
 ctx.font=F(21,'sansb');if(d){ctx.fillStyle=MUTE;spaced(ctx,t.l_take,P,y,3.8)}y+=21+16;
 ctx.font=F(o.ks,'serif');var kl=wrap(ctx,t.take,cw,o.kmax),klh=Math.round(o.ks*1.55);
 if(d){ctx.fillStyle=INK;kl.forEach(function(l,i){ctx.fillText(l,P,y+i*klh+Math.round(klh*0.14))})}y+=kl.length*klh;
 var pts=t.pts.slice(0,o.np);
 if(pts.length){y+=34+g;if(d){ctx.fillStyle=LINE;ctx.fillRect(P,y,cw,2)}y+=2+30;
  ctx.font=F(21,'sansb');if(d){ctx.fillStyle=MUTE;spaced(ctx,t.l_num,P,y,3.8)}y+=21+18;
  ctx.font=F(46,'disp');var nw=0;pts.forEach(function(p){nw=Math.max(nw,ctx.measureText(p[0]).width)});nw=Math.min(Math.max(nw,180),360);
  pts.forEach(function(p,i){ctx.font=F(46,'disp');var num=ellip(ctx,p[0],nw);ctx.font=F(27,'sans');
   var lx=P+nw+28,ll=wrap(ctx,p[1],W-P-lx,2),rh=Math.max(50,ll.length*38);
   if(d){ctx.font=F(46,'disp');ctx.fillStyle=ACC;ctx.fillText(num,P,y);ctx.font=F(27,'sans');ctx.fillStyle=INK2;ll.forEach(function(l,j){ctx.fillText(l,lx,y+8+j*38)})}
   y+=rh+(i<pts.length-1?18:0)})}
 y+=40+g;ctx.font=F(21,'sansb');if(d){ctx.fillStyle=MUTE;spaced(ctx,t.l_sc,P,y,3.8)}y+=21+22;
 var tw=150,bw=(cw-tw-16-4*16)/5;
 t.scores.forEach(function(s,i){var bx=P+i*(bw+16);if(d){ctx.fillStyle='#EAE3D8';rr(ctx,bx,y+30,bw,12,6);ctx.fill();
  var v=Math.max(0,Math.min(5,+s[1]||0));if(v>0){ctx.fillStyle=ACC;rr(ctx,bx,y+30,Math.max(12,bw*v/5),12,6);ctx.fill()}
  ctx.font=F(21,'sans');ctx.fillStyle=INK2;var lab=s[0]+' '+s[1];ctx.fillText(lab,bx+(bw-ctx.measureText(lab).width)/2,y+54)}});
 if(d){ctx.font=F(64,'disp');ctx.fillStyle=INK;var tv=t.total;ctx.fillText(tv,W-P-ctx.measureText(tv).width,y);
  ctx.font=F(20,'sans');ctx.fillStyle=MUTE;ctx.fillText(t.l_tot,W-P-ctx.measureText(t.l_tot).width,y+70)}
 y+=78;return y}
function footer(ctx,D){var t=D.p,bits=qrBits(D),n=D.qr.n,m=Math.max(3,Math.min(5,Math.floor(168/n))),qs=n*m,pad=14,box=qs+2*pad;
 var top=H-P-box-34;ctx.fillStyle=INK;ctx.fillRect(P,top-30,W-2*P,2);
 var qx=W-P-box,qy=top;ctx.fillStyle='#fff';rr(ctx,qx,qy,box,box,10);ctx.fill();ctx.strokeStyle=LINE;ctx.lineWidth=2;rr(ctx,qx+1,qy+1,box-2,box-2,10);ctx.stroke();
 ctx.fillStyle=INK;for(var yy=0;yy<n;yy++)for(var xx=0;xx<n;xx++)if(bits[yy*n+xx]==='1')ctx.fillRect(qx+pad+xx*m,qy+pad+yy*m,m,m);
 ctx.font=F(20,'sans');ctx.fillStyle=MUTE;ctx.fillText(t.scan,qx+(box-ctx.measureText(t.scan).width)/2,qy+box+12);
 var cy=qy+box/2;mark(ctx,P,cy-43,86);var tx=P+86+26,maxw=qx-26-tx;
 ctx.font=F(50,'disp');ctx.fillStyle=INK;ctx.fillText('Paper ',tx,cy-62);ctx.fillStyle=ACC;ctx.fillText('Daily',tx+ctx.measureText('Paper ').width,cy-62);
 ctx.font=F(22,'sans');ctx.fillStyle=MUTE;ctx.fillText(ellip(ctx,t.tag,maxw),tx,cy+2);
 ctx.font=F(20,'sans');ctx.fillText(ellip(ctx,t.durl,maxw),tx,cy+38);return top-30}
function draw(D){var c=document.createElement('canvas');c.width=W;c.height=H;var ctx=c.getContext('2d');
 ctx.textBaseline='top';ctx.fillStyle=BG;ctx.fillRect(0,0,W,H);ctx.fillStyle=ACC;ctx.fillRect(0,0,W,18);
 var limit=footer(ctx,D)-36,np=D.p.pts.length,zh=D.lang==='zh';
 /* shrink until it fits: fewer key numbers, shorter takeaway, smaller title */
 var opts=[];[np,2,1,0].forEach(function(k){if(k<=np)[[64,zh?36:34,3],[58,zh?34:32,3],[54,zh?32:30,2]].forEach(function(a){opts.push({np:k,ts:a[0],ks:a[1],kmax:a[2]})})});
 var o=opts[opts.length-1];for(var i=0;i<opts.length;i++){if(layout(ctx,D,opts[i])<=limit){o=opts[i];break}}
 /* spread leftover height between the sections so short posters don't leave a hole above the footer */
 var slack=limit-layout(ctx,D,o);o.gap=Math.max(0,Math.min(44,slack/(o.np?3:2)));o.draw=true;layout(ctx,D,o);
 return new Promise(function(res,rej){if(!c.toBlob)return rej(new Error('toBlob'));c.toBlob(function(b){b?res(b):rej(new Error('blob'))},'image/png')})}
window.PDPoster=function(D){return loadFonts(D).then(function(){return draw(D)})};
})();
